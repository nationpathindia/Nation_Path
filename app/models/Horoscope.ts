//////////////////////////////////////////////////////////////
// DUPLICATE PROTECTION
//
// Same zodiac + period + language + date range
// cannot create duplicate CMS entry.
//
//////////////////////////////////////////////////////////////

HoroscopeSchema.index(

  {

    zodiac: 1,

    "meta.period": 1,

    "meta.language": 1,

    "meta.startDate": 1,

    "meta.endDate": 1,

  },

  {

    unique: true,

  }

);


