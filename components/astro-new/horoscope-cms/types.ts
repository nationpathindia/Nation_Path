//////////////////////////////////////////////////////////////
// MAIN CMS DATA CONTRACT
//
// EXACT FINAL OUTPUT OF:
//
// buildHoroscopeData()
//
// This is the main contract consumed by:
//
// CmsHoroscopeExperience
// HoroscopeHero
// HoroscopeEditorial
// HoroscopeInsights
// HoroscopeIntelligencePanel
// HoroscopeLifeCards
// HoroscopeLucky
// HoroscopePlanetary
// HoroscopeVedic
// HoroscopeRemedy
// HoroscopeCompatibility
// HoroscopePremium
// ZodiacExplorerPanel
//
//////////////////////////////////////////////////////////////

export interface CmsHoroscopeData {

  ////////////////////////////////////////////////////////////
  // META
  ////////////////////////////////////////////////////////////

  meta?: CmsHoroscopeMeta;

  ////////////////////////////////////////////////////////////
  // CURRENT ZODIAC MASTER
  //
  // IMPORTANT:
  //
  // This is the normalized MongoDB Zodiac Master
  // for the CURRENT horoscope sign.
  //
  // It is NOT the Horoscope CMS identity block.
  //
  ////////////////////////////////////////////////////////////

  zodiac?: CmsZodiacMaster | null;

  ////////////////////////////////////////////////////////////
  // BASIC HOROSCOPE CMS FIELDS
  //
  // These come directly from Horoscope CMS content.
  //
  ////////////////////////////////////////////////////////////

  slug?: string;

  symbol?: string;

  element?: string;

  modality?: string;

  rulingPlanet?: string;

  ////////////////////////////////////////////////////////////
  // HOROSCOPE CONTENT MODULES
  ////////////////////////////////////////////////////////////

  hero?: CmsHoroscopeHero;

  identity?: CmsHoroscopeIdentity;

  traits?: CmsHoroscopeTraits;

  editorial?: CmsHoroscopeEditorial;

  life?: CmsHoroscopeLife;

  insights?: CmsHoroscopeInsights;

  planets?: CmsHoroscopePlanet[];

  ////////////////////////////////////////////////////////////
  // OTHER CMS MODULES
  ////////////////////////////////////////////////////////////

  lucky?: CmsHoroscopeLucky;

  remedy?: CmsHoroscopeRemedy;

  vedic?: CmsHoroscopeVedic;

  compatibility?: CmsHoroscopeCompatibility;

  premium?: CmsHoroscopePremium;

  ////////////////////////////////////////////////////////////
  // SEO
  ////////////////////////////////////////////////////////////

  seo?: CmsHoroscopeSEO;

  ////////////////////////////////////////////////////////////
  // MEDIA
  ////////////////////////////////////////////////////////////

  media?: CmsHoroscopeMedia;

  ////////////////////////////////////////////////////////////
  // ANALYTICS
  ////////////////////////////////////////////////////////////

  analytics?: CmsHoroscopeAnalytics;

  ////////////////////////////////////////////////////////////
  // 12-SIGN ZODIAC EXPLORER
  //
  // Same normalized Zodiac Master source.
  //
  ////////////////////////////////////////////////////////////

  zodiacList?: CmsZodiacItem[];

  ////////////////////////////////////////////////////////////
  // LANGUAGE
  ////////////////////////////////////////////////////////////

  language?: HoroscopeLanguage;
}


