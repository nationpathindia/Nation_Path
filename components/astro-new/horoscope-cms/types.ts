//////////////////////////////////////////////////////////////
// ZODIAC MASTER
//
// THIS INTERFACE MUST MATCH:
//
// mapZodiacMaster()
//
// IN:
//
// Horoscope Content Service
//
// IMPORTANT:
//
// These fields are TOP LEVEL because the service produces:
//
// {
//   zodiac,
//   slug,
//   names,
//   identity,
//   nameInitials,
//   element,
//   modality,
//   rulingPlanet,
//   media,
//   symbol
// }
//
// DO NOT move nameInitials into identity here.
//
// DO NOT move modality into identity here.
//
// DO NOT invent additional calculated fields.
//
//////////////////////////////////////////////////////////////

export interface CmsZodiacMaster {

  ////////////////////////////////////////////////////////////
  // IDENTIFIERS
  ////////////////////////////////////////////////////////////

  zodiac?: string;

  slug?: string;

  ////////////////////////////////////////////////////////////
  // NAMES
  ////////////////////////////////////////////////////////////

  names?: {

    english?: string;

    hindi?: string;

    sanskrit?: string;
  };

  ////////////////////////////////////////////////////////////
  // IDENTITY
  //
  // Exact normalized service fields.
  //
  ////////////////////////////////////////////////////////////

  identity?: {

    rashi?: string;

    sanskritName?: string;

    dates?: string;

    description?: string;

    energy?: string;
  };

  ////////////////////////////////////////////////////////////
  // VEDIC NAME INITIALS
  //
  // IMPORTANT:
  //
  // TOP LEVEL.
  //
  // Source:
  //
  // MongoDB Zodiac.nameInitials
  //
  // NEVER CALCULATE.
  // NEVER GENERATE.
  // NEVER DERIVE.
  //
  ////////////////////////////////////////////////////////////

  nameInitials?: string[];

  ////////////////////////////////////////////////////////////
  // ASTRO IDENTITY
  //
  // TOP LEVEL.
  //
  ////////////////////////////////////////////////////////////

  element?: string;

  modality?: string;

  rulingPlanet?: string;

  ////////////////////////////////////////////////////////////
  // MEDIA
  //
  // Exact normalized service structure.
  //
  ////////////////////////////////////////////////////////////

  media?: {

    icon?: string;

    banner?: string;
  };

  ////////////////////////////////////////////////////////////
  // SYMBOL
  //
  // Normalized from:
  //
  // 1. media.icon
  // 2. symbol
  //
  ////////////////////////////////////////////////////////////

  symbol?: string;
}


